#!/usr/bin/env node
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const configPath = resolve(root, "Config/AppIdentity.json");
const config = JSON.parse(readFileSync(configPath, "utf8"));
const { name, author, bundleIdentifier, slug, urlScheme, backupExtension, repository, signingIdentity, channels, updates } = config;
for (const [key, value] of Object.entries({ name, author, bundleIdentifier, slug, urlScheme, backupExtension, repository, signingIdentity })) {
  if (typeof value !== "string" || !value.trim() || /[\r\n\\"$]/.test(value)) throw new Error(`Invalid ${key}`);
}
if (!/^[\p{L}\p{N}][\p{L}\p{N} _.-]*$/u.test(name)) throw new Error("Invalid product name");
if (!/^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/.test(repository)) throw new Error("Invalid repository");
if (!/^[a-zA-Z][a-zA-Z0-9.-]+$/.test(bundleIdentifier)) throw new Error("Invalid bundleIdentifier");
for (const value of [slug, urlScheme, backupExtension]) {
  if (!/^[a-z][a-z0-9-]*$/.test(value)) throw new Error("Invalid slug, scheme or extension");
}
for (const channel of ["stable", "development", "beta"]) {
  const item = channels[channel];
  if (!item || !/^( [A-Za-z0-9 -]+)?$/.test(item.nameSuffix) || !/^(\.[a-z0-9.-]+)?$/.test(item.bundleSuffix)) {
    throw new Error(`Invalid channel: ${channel}`);
  }
}
if (!updates || typeof updates.enabled !== "boolean"
    || !(updates.repository === null || (typeof updates.repository === "string"
      && /^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/.test(updates.repository)))) {
  throw new Error("Invalid updates configuration");
}
if (updates.enabled && updates.repository === null) throw new Error("Enabled updates require a repository");
const identity = (channel) => ({
  name: name + channels[channel].nameSuffix,
  bundleIdentifier: bundleIdentifier + channels[channel].bundleSuffix,
});
if (process.argv.includes("--value")) {
  const key = process.argv[process.argv.indexOf("--value") + 1];
  if (!(key in config) || typeof config[key] !== "string") throw new Error(`Unknown value ${key}`);
  process.stdout.write(config[key]);
  process.exit(0);
}
if (process.argv.includes("--channel")) {
  const channel = process.argv[process.argv.indexOf("--channel") + 1];
  if (!(channel in channels)) throw new Error("Unknown channel");
  process.stdout.write(JSON.stringify(identity(channel)));
  process.exit(0);
}
const outputs = new Map();
const json = (value) => JSON.stringify(value, null, 2) + "\n";
const q = JSON.stringify;
outputs.set("Tinycast/Platform/AppIdentity.generated.swift", `// Generated by Scripts/sync-identity.mjs from Config/AppIdentity.json.
import Foundation

enum AppIdentity {
    static let name = ${q(name)}
    static let author = ${q(author)}
    static let bundleIdentifier = ${q(bundleIdentifier)}
    static let developmentBundleIdentifier = ${q(identity("development").bundleIdentifier)}
    static let betaBundleIdentifier = ${q(identity("beta").bundleIdentifier)}
    static let slug = ${q(slug)}
    static let urlScheme = ${q(urlScheme)}
    static let backupExtension = ${q(backupExtension)}
    static let updatesEnabled = ${updates.enabled}
    static let updateRepository: String? = ${updates.repository === null ? "nil" : q(updates.repository)}
    static let repository = ${q(repository)}
    static let repositoryURL = URL(string: "https://github.com/\\(repository)")!
}
`);
outputs.set("Config/Identity.generated.yml", `# Generated by Scripts/sync-identity.mjs.
settings:
  base:
    APP_DISPLAY_NAME: ${q(name)}
    APP_URL_SCHEME: ${q(urlScheme)}
    APP_BACKUP_EXTENSION: ${q(backupExtension)}
    APP_BACKUP_IDENTIFIER: ${q(bundleIdentifier + ".backup")}
    CODE_SIGN_IDENTITY: ${q(signingIdentity)}
  configs:
    Debug:
      PRODUCT_NAME: ${q(identity("development").name)}
      PRODUCT_BUNDLE_IDENTIFIER: ${q(identity("development").bundleIdentifier)}
    Release:
      PRODUCT_NAME: ${q(identity("stable").name)}
      PRODUCT_BUNDLE_IDENTIFIER: ${q(identity("stable").bundleIdentifier)}
`);
outputs.set("Scripts/raycast-runtime/src/app-identity.generated.js", `// Generated by Scripts/sync-identity.mjs.\nexport const appIdentity = ${json({ name, slug, urlScheme })};\n`);

for (const file of ["launch.json", "tasks.json"]) {
  const template = readFileSync(resolve(root, `Config/${file}.template`), "utf8");
  outputs.set(`.vscode/${file}`, template.replaceAll("{developmentName}", identity("development").name).replaceAll("{appName}", name));
}

const token = /\{appName\}|\{author\}|\{backupExtension\}|%(?:(\d+)\$)?(?:lld|llu|ld|lu|zd|zu|d|u|f|g|@)/g;
const expand = (text) => text.replaceAll("{appName}", name).replaceAll("{author}", author).replaceAll("{backupExtension}", backupExtension);
function formatEntry(key, entry) {
  const oldPositions = new Map();
  const brandPositions = new Map();
  let oldIndex = 0, nextIndex = 0;
  const formattedKey = key.replace(token, (match, explicit) => {
    nextIndex++;
    if (match.startsWith("{")) {
      const positions = brandPositions.get(match) ?? [];
      positions.push(nextIndex);
      brandPositions.set(match, positions);
      return "%@";
    }
    oldIndex++;
    oldPositions.set(explicit ? Number(explicit) : oldIndex, nextIndex);
    return match.replace(/%\d+\$/, "%");
  });
  const result = structuredClone(entry);
  for (const localization of Object.values(result.localizations ?? {})) {
    if (!localization.stringUnit) throw new Error(`Unsupported branded translation structure: ${key}`);
    let original = 0;
    const used = new Map();
    localization.stringUnit.value = localization.stringUnit.value.replace(token, (match, explicit) => {
      if (match.startsWith("{")) {
        const positions = brandPositions.get(match);
        if (!positions) throw new Error(`Translation adds ${match}: ${key}`);
        const count = used.get(match) ?? 0;
        used.set(match, count + 1);
        return `%${positions[Math.min(count, positions.length - 1)]}$@`;
      }
      original++;
      const position = oldPositions.get(explicit ? Number(explicit) : original);
      if (!position) throw new Error(`Unknown format argument: ${key}`);
      return `%${position}$${match.replace(/^%(?:\d+\$)?/, "")}`;
    });
  }
  return [formattedKey, result];
}
for (const table of ["Localizable", "InfoPlist"]) {
  const source = JSON.parse(readFileSync(resolve(root, `Config/Localization/${table}.xcstrings`), "utf8"));
  const strings = {};
  for (const [key, entry] of Object.entries(source.strings)) {
    strings[expand(key)] = JSON.parse(expand(JSON.stringify(entry)));
  }
  if (table === "Localizable") {
    for (const [key, entry] of Object.entries(source.strings)) {
      if (!key.includes("{appName}") && !key.includes("{author}") && !key.includes("{backupExtension}")) continue;
      const [formattedKey, formatted] = formatEntry(key, entry);
      strings[formattedKey] ??= formatted;
    }
  }
  outputs.set(`Tinycast/Resources/${table}.xcstrings`, json({ ...source, strings: Object.fromEntries(Object.entries(strings).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)) }));
}
let stale = false;
for (const [path, content] of outputs) {
  const target = resolve(root, path);
  let previous;
  try { previous = readFileSync(target, "utf8"); } catch {}
  if (previous === content) continue;
  if (check) { console.error(`Out of date: ${path}`); stale = true; }
  else { mkdirSync(dirname(target), { recursive: true }); writeFileSync(target, content); }
}
if (stale) process.exit(1);
if (!check && !process.argv.includes("--write-only")) {
  const result = spawnSync("xcodegen", ["generate"], { cwd: root, stdio: "inherit" });
  if (result.status !== 0) process.exit(result.status ?? 1);
  const runtime = spawnSync("pnpm", ["--config.verify-deps-before-run=false", "run", "build"], {
    cwd: resolve(root, "Scripts/raycast-runtime"), stdio: "inherit",
  });
  if (runtime.status !== 0) process.exit(runtime.status ?? 1);
}
console.log(check ? "App identity is synchronized." : "App identity, Xcode project and extension runtime synchronized.");
